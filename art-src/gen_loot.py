INK = '#05060c'
def hx(c):
    c = c.lstrip('#'); return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4)) + (255,)
def image(rows, pal, name):
    im = Image.new('RGBA', (14, 14), (0, 0, 0, 0))
    assert len(rows) == 14, (name, len(rows))
    for y, r in enumerate(rows):
        assert len(r) == 14, (name, y, len(r))
        for x, ch in enumerate(r):
            if ch != '.': im.putpixel((x, y), hx(INK if ch == 'o' else pal[ch]))
    return im
